import ufl

def StressNonLin(u):
  I = ufl.variable(ufl.Identity(nsd))
  F = ufl.variable(I + ufl.grad(u))
  C = ufl.variable(F.T * F)
  Ic = ufl.variable(ufl.tr(C))
  J = ufl.variable(ufl.det(F))
  energy = (mu / 2) * (Ic - 2 - 2*ufl.ln(J)) + (lmd / 2) * (J-1)**2
  #energy = (mu / 2) * (Ic - 3) + (lmd / 4) * (J**2-1) - (lmd/2 + mu)*ufl.ln(J)
  P = ufl.diff(energy, F)
  return ufl.variable((1/J)*P*F.T)

def SolveElasNonLin(mesh, bforce, sforce, flag_quads, nsteps_load=1, orderU=1):

    print( "|> Solving Non-Linear Elasticity problem with CG (primal) formulation\n")

    W = VectorFunctionSpace(mesh, "CG", orderU)

    u = Function(W)
    v = TestFunction(W)

    x = SpatialCoordinate(mesh)

    bcall = [DirichletBC(W, nodisp, tag_left)]

    dalpha = 1.0 / nsteps_load
    alpha = dalpha
    for n in range(nsteps_load):
      print('|> Step %d | Solving for %0.1f percent of Maximum load' %(n+1, 100 * dalpha * (n+1)))
      sigma = StressNonLin(u)
      Res  = ufl.inner(sigma, sym(grad(v)) + 0.5*(grad(v).T*grad(u) + grad(u).T*grad(v)))*dx(degree=4)
      Res -= ufl.inner(bforce(x), v)*dx + ufl.inner(Constant(alpha)*sforce(x), v)*ds(tag_right, degree=4)
      Jac = derivative(Res, u)
      solve(Res == 0, u, J=Jac, bcs=bcall, solver_parameters=solpet)
      alpha += dalpha

    return u

